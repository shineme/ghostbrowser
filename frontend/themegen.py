#!/usr/bin/env python3
"""Theme tokenizer for GhostBrowser (v0.9.3).

Rewrites every literal colour in src/style.css and src/graphite.css (and a few
pastel literals in .tsx inline styles) into a CSS custom property that holds
the colour as an "r,g,b" triplet:

    #A78BFA              -> rgb(var(--k-a78bfa))
    rgba(124,140,255,.12) -> rgba(var(--k-7c8cff),.12)

Dark keeps the original values. The light and gray themes get the same
palette remapped by lightness (hue and saturation kept), so tints, hovers and
hairlines flip polarity together. Black-ish translucent colours are shadows or
scrims: their colour stays and their alpha is scaled by --shk per theme.
White text on a coloured fill (primary buttons, glyph tiles, counters) stays
white. Output: src/themes-gen.css (tokens). Hand-tuned semantic overrides live
in src/themes.css. Idempotent: run on the original files only (it refuses when
tokens are already present).
"""
import colorsys, re, sys, pathlib

SRC = pathlib.Path(__file__).parent / 'src'
FILES = ['style.css', 'graphite.css']

HEX = re.compile(r'#([0-9a-fA-F]{6}|[0-9a-fA-F]{3})\b')
RGBA = re.compile(r'rgba?\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*(?:,\s*([0-9.]+)\s*)?\)')

def norm(h):
    h = h.lower()
    if len(h) == 3:
        h = ''.join(c * 2 for c in h)
    return h

def to_rgb(h):
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))

def hexs(rgb):
    return '%02x%02x%02x' % rgb

def interp(pts, x):
    for (x0, y0), (x1, y1) in zip(pts, pts[1:]):
        if x <= x1:
            return y0 + (y1 - y0) * (x - x0) / (x1 - x0)
    return pts[-1][1]

# lightness maps (HSL L in 0..100)
LIGHT = [(0, 100), (3, 100), (6, 98.6), (9, 96.8), (12, 94.2), (16, 91.5), (22, 87), (30, 79),
         (40, 66), (50, 53), (60, 43), (70, 34), (80, 25), (90, 15), (100, 5)]
GRAY = [(0, 13), (3, 15.5), (6, 18), (9, 20.5), (12, 23.5), (16, 27), (25, 34), (40, 46),
        (60, 64), (80, 82), (100, 100)]

def remap(rgb, pts, sat_band):
    r, g, b = (c / 255 for c in rgb)
    h, l, s = colorsys.rgb_to_hls(r, g, b)
    L = interp(pts, l * 100) / 100
    if s > .35 and sat_band:  # colourful: keep it colourful, never mud or chalk
        lo, hi = sat_band
        if .2 < l < .92:
            L = min(max(L, lo), hi)
    r, g, b = colorsys.hls_to_rgb(h, L, s)
    return tuple(round(c * 255) for c in (r, g, b))

def is_shade(rgb):
    r, g, b = rgb
    return max(rgb) < 48  # near-black: shadow / scrim colour

tokens = {}  # hex -> rgb

def tok(rgb):
    h = hexs(rgb)
    tokens[h] = rgb
    return f'var(--k-{h})'

COLORED_FILL = re.compile(r'background:\s*(var\(--(spectral|av|a1|bad|ok)\)|linear-gradient\(135deg,\s*#ff4d63)|rgba\(0,\s*0,\s*0,\s*\.(5|6|7)')

def rewrite_rule(rule):
    keep_white = bool(COLORED_FILL.search(rule))

    def rgba_sub(m):
        rgb = tuple(int(m.group(i)) for i in (1, 2, 3))
        a = m.group(4)
        if a is None:
            return f'rgb({tok(rgb)})'
        decl = re.split(r'[;{]', rgba_src[:m.start()])[-1]
        if is_shade(rgb) and re.search(r'(shadow|filter)\s*:', decl) or rgb == (0, 0, 0):
            return f'rgba({rgb[0]},{rgb[1]},{rgb[2]},calc({a} * var(--shk)))'
        if rgb == (255, 255, 255) and keep_white:
            return m.group(0)
        return f'rgba({tok(rgb)},{a})'

    rgba_src = rule
    out = RGBA.sub(rgba_sub, rule)

    def hex_sub(m):
        h = norm(m.group(1))
        rgb = to_rgb(h)
        pre = out_src[max(0, m.start() - 40):m.start()]
        if h == 'ffffff' and (keep_white or re.search(r'background:\s*$', pre)):
            return m.group(0)
        if re.search(r'mask[^;]*$', pre):  # masks only read alpha
            return m.group(0)
        if h == '000000':
            return 'rgba(0,0,0,var(--shk))'
        return f'rgb({tok(rgb)})'

    out_src = out
    out = HEX.sub(hex_sub, out)
    return out

def process(text):
    # split into rules at '}' so a rule's context (its background) is known;
    # also protect the hex in url()/comments.
    parts = re.split(r'(\})', text)
    res = []
    for p in parts:
        if p == '}':
            res.append(p)
            continue
        # leave comments alone
        segs = re.split(r'(/\*.*?\*/)', p, flags=re.S)
        res.append(''.join(s if s.startswith('/*') else rewrite_rule(s) for s in segs))
    return ''.join(res)

def main():
    for f in FILES:
        t = (SRC / f).read_text()
        if 'var(--k-' in t:
            sys.exit(f'{f} already tokenized')
        (SRC / f).write_text(process(t))
    # pastel literals in TSX inline styles
    for f in SRC.glob('*.tsx'):
        t = f.read_text()
        n = re.sub(r"'#(ffb3bc|ffd98a|ffcf8a|c9d1ff|ff8a9a|6E6E76|2A2A30)'",
                   lambda m: f"'rgb({tok(to_rgb(norm(m.group(1))))})'", t)
        if n != t:
            f.write_text(n)
    lines = ['/* generated by themegen.py: literal colours as r,g,b tokens. Do not edit; edit themes.css. */']
    def block(sel, fn, shk):
        lines.append(f'{sel} {{')
        lines.append(f'  --shk: {shk};')
        for h, rgb in sorted(tokens.items()):
            c = fn(rgb)
            lines.append(f'  --k-{h}: {c[0]},{c[1]},{c[2]};')
        lines.append('}')
    block(':root', lambda c: c, 1)
    block(':root[data-theme="light"]', lambda c: remap(c, LIGHT, (.30, .52)), .32)
    block(':root[data-theme="gray"]', lambda c: remap(c, GRAY, None), .72)
    (SRC / 'themes-gen.css').write_text('\n'.join(lines) + '\n')
    print(len(tokens), 'tokens')

main()
